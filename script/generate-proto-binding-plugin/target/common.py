"""
Naming and comment helpers shared by every target.
"""

from schema import GenerateError, Message, Package, words

HEADER = "Code generated by generate-proto-binding. DO NOT EDIT."


def upper_first(text: str) -> str:
    return text[:1].upper() + text[1:]


def pascal(name: str) -> str:
    return "".join(upper_first(part) for part in words(name))


def camel(name: str) -> str:
    text = pascal(name)
    return text[:1].lower() + text[1:]


def function_name(prefix: str, message: Message) -> str:
    return f"{prefix}{upper_first(message.pkg)}{message.name}"


def option(options: dict[str, str], key: str) -> str:
    if not options.get(key):
        raise GenerateError(f"missing plugin option {key}")
    return options[key]


def block(lines: list[str], indent: str = "") -> str:
    if not lines:
        return ""
    body = "".join(f"{indent} * {line}\n" for line in lines)
    return f"{indent}/**\n{body}{indent} */\n"


def slashes(lines: list[str], indent: str = "") -> str:
    return "".join(f"{indent}// {line}\n" for line in lines)


def outside_refs(group: Package) -> dict[str, list[str]]:
    """
    Groups the names a package borrows from other packages by the package that declares them.
    """
    found: dict[str, set[str]] = {}
    for message in group.messages:
        for item in message.fields:
            if item.ref is not None and item.ref.pkg != group.name:
                found.setdefault(item.ref.pkg, set()).add(item.ref.name)
    return {pkg: sorted(found[pkg]) for pkg in sorted(found)}
